"""Keep the agent-read docs honest.

Agents and humans copy what these docs say. Each check below turns one kind of
doc claim into something CI verifies:

(a) every backticked repo path exists;
(b) every ``wappa`` import in a fenced python block resolves;
(c) every fenced python block compiles;
(d) retired names stay retired: ``recipient=`` on Messenger ``send_*`` calls,
    and ``LOG_LEVEL`` / ``API_VERSION`` / ``ENVIRONMENT`` as documented env
    vars (Settings reads ``SYSTEM_LOG_LEVEL``, ``META_API_VERSION`` and
    ``SYSTEM_ENVIRONMENT``).
"""

from __future__ import annotations

import ast
import importlib
import re
import subprocess
from dataclasses import dataclass
from pathlib import Path

import pytest

from wappa.domain.interfaces import IMessenger

REPO = Path(__file__).resolve().parents[1]

# ── Doc set ──────────────────────────────────────────────────────────────────


def _markdown_docs() -> list[Path]:
    docs = [
        REPO / name
        for name in ("README.md", "AGENTS.md", "CODING_STANDARDS.md", "CONTEXT.md")
    ]
    docs.append(REPO / "ARCHITECTURE.md")
    docs.extend(sorted((REPO / "wappa").rglob("ARCHITECTURE.md")))
    docs.append(REPO / "docs" / "public-contract.md")
    docs.extend(sorted(REPO.glob(".agents/skills/wappa-*/**/*.md")))
    return [doc for doc in docs if doc.is_file()]


def _env_examples() -> list[Path]:
    return sorted(REPO.glob("wappa/cli/examples/*/.env.example"))


MARKDOWN_DOCS = _markdown_docs()
ENV_EXAMPLES = _env_examples()


def _rel(path: Path) -> str:
    return path.relative_to(REPO).as_posix()


# ── Markdown parsing ─────────────────────────────────────────────────────────

_FENCE = re.compile(r"^(?P<indent>\s*)(?P<fence>`{3,}|~{3,})(?P<info>[^`]*)$")


@dataclass(frozen=True)
class CodeBlock:
    doc: Path
    line: int  # 1-based line of the first code line
    lang: str
    source: str

    @property
    def where(self) -> str:
        return f"{_rel(self.doc)}:{self.line}"


def _split(doc: Path) -> tuple[list[CodeBlock], list[tuple[int, str]]]:
    """Return the fenced code blocks and the prose lines (outside fences)."""
    blocks: list[CodeBlock] = []
    prose: list[tuple[int, str]] = []
    lines = doc.read_text(encoding="utf-8").splitlines()
    i = 0
    while i < len(lines):
        match = _FENCE.match(lines[i])
        if not match:
            prose.append((i + 1, lines[i]))
            i += 1
            continue
        fence, indent = match["fence"], len(match["indent"])
        lang = match["info"].strip().split(" ")[0].lower()
        body: list[str] = []
        start = i + 2
        i += 1
        while i < len(lines):
            stripped = lines[i].strip()
            if stripped.startswith(fence[0] * len(fence)) and not stripped.strip(
                fence[0]
            ):
                break
            body.append(lines[i][indent:] if lines[i][:indent].isspace() else lines[i])
            i += 1
        i += 1
        blocks.append(CodeBlock(doc, start, lang, "\n".join(body) + "\n"))
    return blocks, prose


def _python_blocks() -> list[CodeBlock]:
    return [
        block
        for doc in MARKDOWN_DOCS
        for block in _split(doc)[0]
        if block.lang in ("python", "py", "python3")
    ]


PYTHON_BLOCKS = _python_blocks()
_COMPILE_FLAGS = ast.PyCF_ONLY_AST | ast.PyCF_ALLOW_TOP_LEVEL_AWAIT


def _parse(block: CodeBlock) -> ast.Module:
    tree = compile(block.source, block.where, "exec", flags=_COMPILE_FLAGS)
    assert isinstance(tree, ast.Module)
    return tree


# ── (a) backticked paths exist ───────────────────────────────────────────────

_INLINE_CODE = re.compile(r"(?<!`)`([^`\n]+)`(?!`)")
_EXTENSION = re.compile(r"\.[A-Za-z][A-Za-z0-9]{0,9}$")
# Intentional non-paths that look like paths, with the reason. Keep it short.
PATH_ALLOWLIST: dict[str, str] = {
    "app/": "inside a project generated by `wappa init`",
    "app/scores/": "inside a project generated by `wappa init`",
    "app/main.py": "inside a project generated by `wappa init`",
    "references/": "per-skill layout under wappa/cli/skills/<name>/",
    "agents/openai.yaml": "per-skill layout under wappa/cli/skills/<name>/",
    "evals/evals.json": "per-skill layout under wappa/cli/skills/<name>/",
    "instagram_conversations_example/tests/test_form_intake.py": (
        "lives in the separate Wappa examples repo"
    ),
}


def _looks_like_path(token: str) -> bool:
    if "/" not in token or any(c.isspace() for c in token):
        return False
    if token.startswith(("/", "http:", "https:", "~", "$", "-")) or "://" in token:
        return False  # routes, URLs, home/env paths, CLI flags
    if any(c in token for c in "*?[]{}<>|()=,'\"@"):
        return False  # globs, placeholders, expressions
    if token.startswith("../"):
        return True
    last = token.rstrip("/").rsplit("/", 1)[-1]
    return token.endswith("/") or bool(_EXTENSION.search(last))


def _normalise(token: str) -> str:
    token = re.sub(r"::.*$", "", token)  # pytest node ids
    token = re.sub(r"#.*$", "", token)  # anchors
    token = re.sub(r":\d+(-\d+)?$", "", token)  # line numbers
    return token.removeprefix("./")


def _git_ignored(token: str) -> bool:
    """Local-only artifacts (``dist/``, ``logs/``) are valid claims even on a
    fresh checkout where they do not exist yet."""
    try:
        result = subprocess.run(
            ["git", "check-ignore", "-q", "--no-index", token],
            cwd=REPO,
            capture_output=True,
            check=False,
        )
    except OSError:
        return False
    return result.returncode == 0


def _exists(token: str, doc: Path) -> bool:
    bases = (REPO, doc.parent, REPO / "wappa")
    return any((base / token).exists() for base in bases) or _git_ignored(token)


def _path_claims() -> list[tuple[str, str]]:
    claims: list[tuple[str, str]] = []
    for doc in MARKDOWN_DOCS:
        for lineno, line in _split(doc)[1]:
            for raw in _INLINE_CODE.findall(line):
                token = raw.strip()
                if token in PATH_ALLOWLIST or not _looks_like_path(token):
                    continue
                path = _normalise(token)
                if path and not _exists(path, doc):
                    claims.append((f"{_rel(doc)}:{lineno}", token))
    return claims


def test_doc_set_is_not_empty() -> None:
    assert len(MARKDOWN_DOCS) >= 8
    assert ENV_EXAMPLES
    assert PYTHON_BLOCKS


def test_backticked_paths_exist() -> None:
    missing = [f"{where}: `{token}`" for where, token in _path_claims()]
    assert not missing, "Backticked paths that do not exist:\n" + "\n".join(missing)


# ── (b) wappa imports resolve, (c) python blocks compile ─────────────────────


def _compile_errors() -> list[str]:
    errors = []
    for block in PYTHON_BLOCKS:
        try:
            _parse(block)
        except SyntaxError as exc:
            line = block.line + (exc.lineno or 1) - 1
            errors.append(f"{_rel(block.doc)}:{line}: {exc.msg}")
    return errors


def _resolves(module: str, name: str | None) -> str | None:
    try:
        mod = importlib.import_module(module)
    except ImportError as exc:
        return f"cannot import module {module} ({exc})"
    if name is None or hasattr(mod, name):
        return None
    try:
        importlib.import_module(f"{module}.{name}")
    except ImportError:
        return f"{module} has no {name}"
    return None


def _import_errors() -> list[str]:
    errors = []
    for block in PYTHON_BLOCKS:
        try:
            tree = _parse(block)
        except SyntaxError:
            continue  # reported by test_python_blocks_compile
        for node in ast.walk(tree):
            if isinstance(node, ast.ImportFrom) and node.level == 0:
                targets = [
                    (node.module or "", alias.name)
                    for alias in node.names
                    if alias.name != "*"
                ]
            elif isinstance(node, ast.Import):
                targets = [(alias.name, None) for alias in node.names]
            else:
                continue
            line = f"{_rel(block.doc)}:{block.line + node.lineno - 1}"
            for module, name in targets:
                if module != "wappa" and not module.startswith("wappa."):
                    continue
                if problem := _resolves(module, name):
                    errors.append(f"{line}: {problem}")
    return errors


def test_python_blocks_compile() -> None:
    errors = _compile_errors()
    assert not errors, "Python blocks that do not compile:\n" + "\n".join(errors)


def test_wappa_imports_in_python_blocks_resolve() -> None:
    errors = _import_errors()
    assert not errors, "Unresolvable wappa imports:\n" + "\n".join(errors)


# ── (d) retired names ────────────────────────────────────────────────────────

MESSENGER_SEND_METHODS = frozenset(
    name for name in dir(IMessenger) if name.startswith("send_")
)
RETIRED_ENV_VARS = ("LOG_LEVEL", "API_VERSION", "ENVIRONMENT")
_RETIRED_ENV_LINE = re.compile(
    r"^\s*#?\s*(?:export\s+)?(?P<key>" + "|".join(RETIRED_ENV_VARS) + r")\s*="
)


def _retired_recipient_calls() -> list[str]:
    hits = []
    for block in PYTHON_BLOCKS:
        try:
            tree = _parse(block)
        except SyntaxError:
            continue  # reported by test_python_blocks_compile
        for node in ast.walk(tree):
            if not isinstance(node, ast.Call):
                continue
            func = node.func
            name = (
                func.attr
                if isinstance(func, ast.Attribute)
                else func.id
                if isinstance(func, ast.Name)
                else None
            )
            if name not in MESSENGER_SEND_METHODS:
                continue
            if any(kw.arg == "recipient" for kw in node.keywords):
                line = block.line + node.lineno - 1
                hits.append(f"{_rel(block.doc)}:{line}: {name}(recipient=...)")
    return hits


def test_messenger_send_calls_do_not_use_retired_recipient_keyword() -> None:
    assert "send_text" in MESSENGER_SEND_METHODS
    hits = _retired_recipient_calls()
    assert not hits, (
        "Messenger send_* calls take a target, not recipient=:\n" + "\n".join(hits)
    )


@pytest.mark.parametrize("env_example", ENV_EXAMPLES, ids=_rel)
def test_env_examples_do_not_document_retired_env_vars(env_example: Path) -> None:
    hits = [
        f"{_rel(env_example)}:{lineno}: {match['key']}"
        for lineno, line in enumerate(env_example.read_text().splitlines(), start=1)
        if (match := _RETIRED_ENV_LINE.match(line))
    ]
    assert not hits, "Retired env vars (use SYSTEM_*/META_*):\n" + "\n".join(hits)


def test_retired_env_vars_are_not_read_by_settings() -> None:
    source = (REPO / "wappa" / "core" / "config" / "settings.py").read_text()
    for name in RETIRED_ENV_VARS:
        assert f'"{name}"' not in source, f"Settings reads {name}; update this test"
